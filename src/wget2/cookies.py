"""Cookie handling: ``--cookie`` strings, ``--cookie-jar`` persistence."""

from __future__ import annotations

import threading
import time
from http.cookies import CookieError, SimpleCookie
from pathlib import Path
from urllib.parse import urlparse

from .errors import FilesystemError
from .log import get_logger
from .util import redact


class CookieStore:
    """A tiny, backend-agnostic cookie jar.

    Loads either ``name=value`` lines or a Netscape ``cookies.txt`` file and
    writes the Netscape format back out, so ``--cookie-jar`` interoperates
    with curl/wget.
    """

    def __init__(self) -> None:
        self._lock = threading.Lock()
        # (domain, name) -> (value, path)
        self._cookies: dict[tuple[str, str], tuple[str, str]] = {}
        self._dirty = False

    # -- loading ---------------------------------------------------------- #
    def load_inline(self, raw: str) -> None:
        for part in raw.split(";"):
            part = part.strip()
            if not part:
                continue
            name, sep, value = part.partition("=")
            if not sep:
                continue
            self.set("", name.strip(), value.strip())

    def load_file(self, path: Path) -> None:
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except FileNotFoundError:
            get_logger("cookies").debug("cookie jar does not exist yet", path=str(path))
            return
        except OSError as exc:
            raise FilesystemError(f"cannot read cookie jar {path}: {exc}") from exc
        loaded = 0
        for line in text.splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                if line.startswith("#HttpOnly_"):
                    line = line[len("#HttpOnly_") :]
                else:
                    continue
            if line.startswith("Set-Cookie:"):
                continue
            fields = line.split("\t")
            if len(fields) == 7:  # Netscape format
                domain, _flag, path_field, _secure, _expiry, name, value = fields
                self.set(domain.lstrip("."), name, value, path=path_field or "/")
                loaded += 1
            elif "=" in line:
                name, _, value = line.partition("=")
                self.set("", name.strip(), value.strip())
                loaded += 1
        get_logger("cookies").debug("cookie jar loaded", path=str(path), cookies=loaded)

    def save(self, path: Path) -> None:
        with self._lock:
            entries = dict(self._cookies)
            dirty = self._dirty
        if not entries and not dirty:
            return
        lines = ["# Netscape HTTP Cookie File", "# Generated by wget2", ""]
        for (domain, name), (value, cookie_path) in sorted(entries.items()):
            lines.append(
                "\t".join(
                    [
                        domain or "localhost",
                        "TRUE" if domain else "FALSE",
                        cookie_path or "/",
                        "FALSE",
                        "0",
                        name,
                        value,
                    ]
                )
            )
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text("\r\n".join(lines) + "\r\n", encoding="utf-8")
        except OSError as exc:
            raise FilesystemError(f"cannot write cookie jar {path}: {exc}") from exc
        get_logger("cookies").debug("cookie jar saved", path=str(path), cookies=len(entries))

    # -- access ----------------------------------------------------------- #
    def set(self, domain: str, name: str, value: str, *, path: str = "/") -> None:
        with self._lock:
            self._cookies[(domain.lower(), name)] = (value, path or "/")
            self._dirty = True
        get_logger("cookies").debug("cookie stored", domain=domain, name=name, value=redact(value))

    def header_for(self, url: str) -> str | None:
        host = (urlparse(url).hostname or "").lower()
        path = urlparse(url).path or "/"
        with self._lock:
            items = dict(self._cookies)
        selected: list[str] = []
        for (domain, name), (value, cookie_path) in sorted(items.items()):
            domain_ok = not domain or host == domain or host.endswith("." + domain)
            path_ok = path.startswith(cookie_path or "/")
            if domain_ok and path_ok:
                selected.append(f"{name}={value}")
        return "; ".join(selected) if selected else None

    def update_from_headers(self, url: str, set_cookie: str | None) -> None:
        """Parse one or more ``Set-Cookie`` headers (newline separated)."""
        if not set_cookie:
            return
        host = (urlparse(url).hostname or "").lower()
        for raw in set_cookie.replace("\r\n", "\n").split("\n"):
            raw = raw.strip()
            if not raw:
                continue
            jar = SimpleCookie()
            try:
                jar.load(raw)
            except CookieError:  # pragma: no cover - malformed header
                continue
            for name, morsel in jar.items():
                domain = (morsel["domain"] or host).lstrip(".").lower()
                self.set(domain, name, morsel.value, path=morsel["path"] or "/")

    def as_dict(self) -> dict[str, str]:
        with self._lock:
            return {name: value for (_domain, name), (value, _p) in self._cookies.items()}


def expiry_now() -> int:  # pragma: no cover - helper for tests
    return int(time.time())
